export function selectProjects(id: string) {
  return id === 'all' ? demoProjects : demoProjects.filter((project) => project.id === id);
}
export function scopedItems<T extends { projectId: string }>(items: readonly T[], id: string): T[] {
  return items.filter((item) => id === 'all' || item.projectId === id);
}
