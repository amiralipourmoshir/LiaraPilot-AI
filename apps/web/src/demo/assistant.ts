export type DemoReply = {
  text: string;
  action?: { label: string; path: string };
  evidence?: string[];
};
export function replyToDemo(input: string): DemoReply {
  const text = input.toLowerCase();
  if (/توکن|رمز|secret|api[_ -]?key|sk-[a-z0-9]/i.test(text))
    return {
      text: 'کلید و رمز را در گفتگو وارد نکنید. در این فاز هیچ اتصال واقعی ذخیره نمی‌شود؛ صفحه اتصال‌ها وضعیت امکانات را نشان می‌دهد.',
      action: { label: 'مشاهده اتصال‌ها', path: '/connections' },
    };
  if (/۵۰۰|500|خطا|اختلال|دیتابیس|مشکل|اطلس|atlas/.test(text))
    return {
      text: 'در سناریوی نمونه اطلس، خطای ECONNREFUSED و پاسخ HTTP 500 ثبت شده‌اند. علت احتمالی، دسترسی نداشتن برنامه به مقصد دیتابیس است. برای نتیجه قطعی باید وضعیت دیتابیس و تنظیمات مقصد بررسی شوند؛ فعلاً پیشنهاد restart نمی‌دهم.',
      action: { label: 'باز کردن رخداد و شواهد', path: '/incidents/demo-incident-01' },
      evidence: ['evidence-log-1', 'evidence-log-2'],
    };
  if (/دیپلوی|deploy|انتشار|منتشر|گیت|github|راه‌اندازی/.test(text))
    return {
      text: 'مسیر طراحی‌شده انتشار از انتخاب مخزن شروع می‌شود: بررسی ساختار، تکمیل تنظیمات، انتخاب منابع معتبر، بازبینی و تأیید، سپس اجرا و بررسی سلامت. اینجا می‌توانید جزئیات یک انتشار نمونه را ببینید؛ هنوز مخزن واقعی تحلیل یا منتشر نمی‌شود.',
      action: { label: 'مشاهده انتشار نمونه', path: '/deployments/demo-deploy-1042' },
    };
  if (/سلامت|وضعیت|پایش|مصرف|منابع|سرویس/.test(text))
    return {
      text: 'در داده‌های نمایشی، فروشگاه نُوا و مستندات پایلوت سالم‌اند؛ سرویس اطلس به بررسی نیاز دارد. نمودارهای پایش از داده ثابت دمو ساخته شده‌اند و از سرویس واقعی خوانده نمی‌شوند.',
      action: { label: 'مشاهده پایش نمایشی', path: '/monitoring' },
    };
  return {
    text: 'من پایلوت هستم؛ این گفتگو پیش‌نمایش تعاملی رابط است و پاسخ‌ها از سناریوهای ثابت می‌آیند. می‌توانید درباره وضعیت سرویس‌ها، خطای ۵۰۰ اطلس یا مسیر انتشار بپرسید. اتصال مدل هوش مصنوعی در فاز پنجم اضافه می‌شود.',
    action: { label: 'دیدن پروژه‌های نمونه', path: '/projects' },
  };
}
